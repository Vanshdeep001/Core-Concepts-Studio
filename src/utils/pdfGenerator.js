/* ═══════════════════════════════════════
   COMBINED STUDY GUIDE PDF GENERATOR
   ═══════════════════════════════════════ */
export function generateStudyGuidePdf(topicKey) {
  // Determine category and merge keys
  let categoryPrefix = '';
  let masterTitle = '';
  let masterModule = '';
  
  if (topicKey.startsWith('os/')) {
    categoryPrefix = 'os/';
    masterTitle = 'Operating Systems (OS) Complete Placement Guide';
    masterModule = 'Operating Systems';
  } else if (topicKey.startsWith('dbms/')) {
    categoryPrefix = 'dbms/';
    masterTitle = 'Database Management Systems (DBMS) Complete Placement Guide';
    masterModule = 'Database Management Systems';
  } else if (topicKey.startsWith('oops/')) {
    categoryPrefix = 'oops/';
    masterTitle = 'Object-Oriented Programming & Design Patterns Complete Placement Guide';
    masterModule = 'Object-Oriented Programming';
  } else if (topicKey.startsWith('networks/')) {
    categoryPrefix = 'networks/';
    masterTitle = 'Computer Networks (CN) Complete Placement Guide';
    masterModule = 'Computer Networks';
  } else if (topicKey.startsWith('systemdesign/')) {
    categoryPrefix = 'systemdesign/';
    masterTitle = 'System Design & High-Scale Architectures Complete Placement Guide';
    masterModule = 'System Design';
  } else {
    categoryPrefix = topicKey;
    masterTitle = 'Technical Interview Prep & CS Fundamentals Master Guide';
    masterModule = 'Interview Prep';
  }

  let keysToMerge = [];
  if (categoryPrefix.endsWith('/')) {
    keysToMerge = Object.keys(NOTES_DATA).filter(k => k.startsWith(categoryPrefix));
  } else {
    keysToMerge = [topicKey];
  }

  const mergedFullNotesSections = [];
  const mergedQuestions = [];
  const mergedKeyPoints = [];
  const mergedFormulas = [];
  const mergedComparisons = [];
  const mergedMnemonics = [];

  keysToMerge.forEach(key => {
    const subData = NOTES_DATA[key];
    if (!subData) return;

    if (subData.fullNotes?.sections) {
      subData.fullNotes.sections.forEach(sec => {
        mergedFullNotesSections.push({
          heading: `${subData.title} - ${sec.heading}`,
          content: sec.content,
          codeSnippet: sec.codeSnippet
        });
      });
    }

    if (subData.interviewPrep?.questions) {
      subData.interviewPrep.questions.forEach(q => {
        mergedQuestions.push({
          q: `[${subData.title}] ${q.q}`,
          a: q.a,
          difficulty: q.difficulty
        });
      });
    }

    if (subData.cheatSheet?.keyPoints) {
      subData.cheatSheet.keyPoints.forEach(p => {
        mergedKeyPoints.push(`[${subData.title}] ${p}`);
      });
    }

    if (subData.cheatSheet?.formulas) {
      subData.cheatSheet.formulas.forEach(f => {
        mergedFormulas.push(`[${subData.title}] ${f}`);
      });
    }

    if (subData.cheatSheet?.comparisons) {
      subData.cheatSheet.comparisons.forEach(c => {
        mergedComparisons.push(c);
      });
    }

    if (subData.cheatSheet?.mnemonics) {
      subData.cheatSheet.mnemonics.forEach(m => {
        mergedMnemonics.push(m);
      });
    }
  });

  const data = {
    title: masterTitle,
    module: masterModule,
    icon: '📘',
    cheatSheet: {
      keyPoints: mergedKeyPoints,
      formulas: mergedFormulas,
      comparisons: mergedComparisons,
      mnemonics: mergedMnemonics
    },
    fullNotes: {
      sections: mergedFullNotesSections
    },
    interviewPrep: {
      questions: mergedQuestions
    }
  };

  const doc = new jsPDF('p', 'mm', 'a4');
  let y = MARGIN.top + 6;

  // 1. Premium Header Title block
  doc.setFillColor(...COLORS.yellow);
  doc.setDrawColor(...COLORS.black);
  doc.setLineWidth(0.8);
  doc.roundedRect(MARGIN.left, y, CONTENT_WIDTH, 16, 2, 2, 'FD');
  
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(...COLORS.black);
  doc.text(cleanTextForPdf(data.title) + " - Placement Study Guide", MARGIN.left + 5, y + 10.5);
  y += 24;

  // Module info tag
  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...COLORS.gray);
  const cleanModule = cleanTextForPdf(data.module);
  doc.text(`Module: ${cleanModule}  |  Type: All-In-One Placement Companion`, MARGIN.left, y);
  y += 8;

  // ----------------------------------------------------
  // PART 1: QUICK REFERENCE & CHEAT SHEET
  // ----------------------------------------------------
  if (data.cheatSheet) {
    y = drawSectionHeading(doc, 'Part 1: Quick Reference & Cheat Sheet', y, COLORS.yellow);
    
    // Key Points
    if (data.cheatSheet.keyPoints?.length) {
      y = drawSubheading(doc, 'Key Points', y);
      data.cheatSheet.keyPoints.forEach((point) => {
        y = checkPageBreak(doc, y, 10);
        
        doc.setFillColor(...COLORS.black);
        doc.circle(MARGIN.left + 4, y - 1, 0.9, 'F');
        
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(9);
        doc.setTextColor(...COLORS.darkGray);
        
        const lines = doc.splitTextToSize(cleanTextForPdf(point), CONTENT_WIDTH - 12);
        for (const line of lines) {
          doc.text(line, MARGIN.left + 8, y);
          y += 5.0;
        }
        y += 1.5;
      });
      y += 3;
    }

    // Formulas & Complexities
    if (data.cheatSheet.formulas?.length) {
      y = drawSubheading(doc, 'Formulas & Complexities', y);
      data.cheatSheet.formulas.forEach((formula) => {
        const fLines = doc.splitTextToSize(cleanTextForPdf(formula), CONTENT_WIDTH - 12);
        const fLineHeight = 4.8;
        const fH = fLines.length * fLineHeight + 6;
        
        y = checkPageBreak(doc, y, fH + 5);
        
        doc.setFillColor(248, 249, 251);
        doc.setDrawColor(200, 200, 200);
        doc.setLineWidth(0.4);
        doc.roundedRect(MARGIN.left + 4, y - 3, CONTENT_WIDTH - 8, fH, 1.5, 1.5, 'FD');
        
        doc.setFont('courier', 'bold');
        doc.setFontSize(8.5);
        doc.setTextColor(30, 30, 46);
        
        let currentY = y + 1.5;
        for (const line of fLines) {
          doc.text(line, MARGIN.left + 8, currentY);
          currentY += fLineHeight;
        }
        y += fH + 2;
      });
      y += 2;
    }

    // Comparisons (Dynamic Auto-wrapping Table)
    if (data.cheatSheet.comparisons?.length) {
      y = drawSubheading(doc, 'Comparisons', y);
      data.cheatSheet.comparisons.forEach((comp) => {
        const colW = (CONTENT_WIDTH - 8) / 2;
        const leftHeader = cleanTextForPdf(comp.left);
        const rightHeader = cleanTextForPdf(comp.right);
        
        const leftHeaderLines = doc.splitTextToSize(leftHeader, colW - 6);
        const rightHeaderLines = doc.splitTextToSize(rightHeader, colW - 6);
        
        const headerLinesMax = Math.max(leftHeaderLines.length, rightHeaderLines.length);
        const headerH = headerLinesMax * 4.5 + 6;
        
        y = checkPageBreak(doc, y, headerH + 20);
        
        // Draw table header cells
        doc.setFillColor(...COLORS.yellow);
        doc.setDrawColor(...COLORS.black);
        doc.setLineWidth(0.8);
        doc.rect(MARGIN.left + 2, y, colW, headerH, 'FD');
        doc.rect(MARGIN.left + 2 + colW, y, colW, headerH, 'FD');
        
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(8.5);
        doc.setTextColor(...COLORS.black);
        
        leftHeaderLines.forEach((line, idx) => {
          doc.text(line, MARGIN.left + 5, y + 4.5 + idx * 4.5);
        });
        rightHeaderLines.forEach((line, idx) => {
          doc.text(line, MARGIN.left + 5 + colW, y + 4.5 + idx * 4.5);
        });
        
        y += headerH;
        
        // Criteria rows
        comp.criteria.forEach((c, ci) => {
          const parts = c.split(' vs ');
          const leftText = cleanTextForPdf(parts[0] || c);
          const rightText = cleanTextForPdf(parts[1] || '');
          
          const leftLines = doc.splitTextToSize(leftText, colW - 6);
          const rightLines = doc.splitTextToSize(rightText, colW - 6);
          
          const maxLines = Math.max(leftLines.length, rightLines.length);
          const rowH = maxLines * 4.5 + 5;
          
          y = checkPageBreak(doc, y, rowH);
          
          const bg = ci % 2 === 0 ? [255, 255, 255] : [245, 245, 250];
          doc.setFillColor(...bg);
          doc.setDrawColor(...COLORS.black);
          doc.setLineWidth(0.6);
          
          doc.rect(MARGIN.left + 2, y, colW, rowH, 'FD');
          doc.rect(MARGIN.left + 2 + colW, y, colW, rowH, 'FD');
          
          doc.setFont('helvetica', 'normal');
          doc.setFontSize(8);
          doc.setTextColor(...COLORS.darkGray);
          
          leftLines.forEach((line, idx) => {
            doc.text(line, MARGIN.left + 5, y + 4.5 + idx * 4.5);
          });
          rightLines.forEach((line, idx) => {
            doc.text(line, MARGIN.left + 5 + colW, y + 4.5 + idx * 4.5);
          });
          
          y += rowH;
        });
        
        y += 6;
      });
    }

    // Mnemonics
    if (data.cheatSheet.mnemonics?.length) {
      y = drawSubheading(doc, 'Mnemonics & Memory Aids', y);
      data.cheatSheet.mnemonics.forEach((m) => {
        const mLines = doc.splitTextToSize(cleanTextForPdf(m), CONTENT_WIDTH - 16);
        const mLineHeight = 4.8;
        const mPadding = 5;
        const mH = mLines.length * mLineHeight + mPadding * 2;
        
        y = checkPageBreak(doc, y, mH + 6);
        
        doc.setFillColor(235, 247, 236);
        doc.setDrawColor(...COLORS.green);
        doc.setLineWidth(0.5);
        doc.roundedRect(MARGIN.left + 4, y - 3, CONTENT_WIDTH - 8, mH, 1.5, 1.5, 'FD');
        
        doc.setFont('helvetica', 'italic');
        doc.setFontSize(8.5);
        doc.setTextColor(40, 115, 45); // Forest green
        
        let currentY = y + mPadding - 1;
        for (const line of mLines) {
          doc.text(`* ${line}`, MARGIN.left + 8, currentY);
          currentY += mLineHeight;
        }
        y += mH + 4;
      });
    }
  }

  // ----------------------------------------------------
  // PART 2: COMPREHENSIVE STUDY NOTES
  // ----------------------------------------------------
  y = checkPageBreak(doc, y, 40);
  y = drawSectionHeading(doc, 'Part 2: Comprehensive Study Notes', y, COLORS.cyan);
  
  if (data.fullNotes?.sections?.length) {
    data.fullNotes.sections.forEach((section, i) => {
      y = drawSubheading(doc, `${i + 1}. ${section.heading}`, y);
      y = drawBodyText(doc, section.content, y, 2);
      
      if (section.codeSnippet) {
        y = drawCodeBlock(doc, section.codeSnippet, y);
      }
      y += 4;
    });
  }

  // ----------------------------------------------------
  // PART 3: PLACEMENT INTERVIEW PREP Q&A
  // ----------------------------------------------------
  y = checkPageBreak(doc, y, 40);
  y = drawSectionHeading(doc, 'Part 3: Placement Interview Prep Q&A', y, COLORS.pink);
  
  if (data.interviewPrep?.questions?.length) {
    data.interviewPrep.questions.forEach((q, i) => {
      y = checkPageBreak(doc, y, 40);
      
      // Question label + difficulty badge
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9.5);
      doc.setTextColor(...COLORS.black);
      
      const qLabel = `Q${i + 1}.`;
      doc.text(qLabel, MARGIN.left, y);
      const labelW = doc.getTextWidth(qLabel) + 3;
      drawDifficultyBadge(doc, q.difficulty, MARGIN.left + labelW, y);
      y += 5.5;

      // Question text
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9.5);
      doc.setTextColor(...COLORS.black);
      const qLines = doc.splitTextToSize(cleanTextForPdf(q.q), CONTENT_WIDTH - 4);
      for (const line of qLines) {
        y = checkPageBreak(doc, y, 7);
        doc.text(line, MARGIN.left + 2, y);
        y += 5.0;
      }
      y += 2.5;

      // Answer block configuration
      doc.setFillColor(...COLORS.lightGray);
      const ansLines = doc.splitTextToSize(cleanTextForPdf(q.a), CONTENT_WIDTH - 16);
      const ansLineHeight = 4.8;
      const ansPadding = 5;
      const ansBlockH = ansLines.length * ansLineHeight + ansPadding * 2;
      
      y = checkPageBreak(doc, y, ansBlockH + 5);
      
      doc.setDrawColor(200, 200, 200);
      doc.setLineWidth(0.4);
      doc.roundedRect(MARGIN.left + 2, y - 3, CONTENT_WIDTH - 4, ansBlockH, 1.5, 1.5, 'FD');
      
      // Left vertical accent bar
      doc.setFillColor(...COLORS.green);
      doc.rect(MARGIN.left + 2, y - 3, 2.5, ansBlockH, 'F');

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      doc.setTextColor(...COLORS.darkGray);
      
      let currentY = y + ansPadding - 1;
      for (const line of ansLines) {
        doc.text(line, MARGIN.left + 8, currentY);
        currentY += ansLineHeight;
      }
      
      y += ansBlockH + 3;
    });
  }

  // ----------------------------------------------------
  // PART 4: PLACEMENT MASTERCLASS (DETAILED NOTES APPENDIX)
  // ----------------------------------------------------
  let appendix = [];
  if (topicKey.startsWith('os/')) {
    appendix = OS_APPENDIX;
  } else if (topicKey.startsWith('dbms/')) {
    appendix = DBMS_APPENDIX;
  } else if (topicKey.startsWith('oops/')) {
    appendix = OOP_APPENDIX;
  } else if (topicKey.startsWith('networks/')) {
    appendix = NETWORKS_APPENDIX;
  } else if (topicKey.startsWith('systemdesign/') || topicKey === 'interview') {
    appendix = SD_APPENDIX;
  }

  if (appendix.length > 0) {
    y = checkPageBreak(doc, y, 40);
    y = drawSectionHeading(doc, 'Part 4: Placement Masterclass (Advanced Concepts)', y, COLORS.green);
    
    appendix.forEach((item) => {
      y = drawSubheading(doc, item.heading, y);
      y = drawBodyText(doc, item.content, y, 2);
      y += 4;
    });
  }

  // Finish PDF layout
  addAllHeaders(doc, data.title, data.module, data.icon, 'Placement Study Guide');
  addAllFooters(doc);
  
  const filename = `${data.title.replace(/[^a-zA-Z0-9 ]/g, '').replace(/\s+/g, '_')}_Study_Guide.pdf`;
  doc.save(filename);
  return filename;
}

