/**
 * cleanTextForPdf: Strips emojis and translates extended Unicode chars
 * (Greek, math symbols, etc.) into clean, printable WinAnsi ASCII equivalents.
 */
function cleanTextForPdf(str) {
  if (!str) return '';
  
  let clean = str
    .replace(/α/g, 'alpha')
    .replace(/β/g, 'beta')
    .replace(/τ/g, 'tau')
    .replace(/θ/g, 'theta')
    .replace(/∅/g, 'null')
    .replace(/·/g, '*')
    .replace(/➔/g, '->')
    .replace(/Δ/g, 'delta')
    .replace(/Σ/g, 'sum')
    .replace(/≤/g, '<=')
    .replace(/≥/g, '>=')
    .replace(/≠/g, '!=')
    .replace(/≈/g, '~')
    .replace(/°/g, ' degrees')
    .replace(/±/g, '+/-')
    .replace(/¹/g, '^1')
    .replace(/²/g, '^2')
    .replace(/³/g, '^3')
    .replace(/⁻/g, '-')
    .replace(/⁺/g, '+')
    .replace(/π/g, 'pi')
    .replace(/½/g, '1/2')
    .replace(/—/g, '-')
    .replace(/–/g, '-')
    .replace(/•/g, '*');

  // Strip standard emojis
  clean = clean.replace(/[\u{1F300}-\u{1F9FF}\u{2600}-\u{26FF}\u{2700}-\u{27BF}\u{1F000}-\u{1FFFF}\u{1F600}-\u{1F64F}\u{1F680}-\u{1F6FF}\u{1F1E6}-\u{1F1FF}]/gu, '');
  
  // Strip non-WinAnsi (>255) characters, converting known ones
  let finalClean = '';
  for (let i = 0; i < clean.length; i++) {
    const code = clean.charCodeAt(i);
    if (code <= 255) {
      finalClean += clean[i];
    } else {
      if (code === 0x2192) { // right arrow →
        finalClean += '->';
      } else if (code === 0x221E) { // infinity ∞
        finalClean += 'infinity';
      } else if (code === 0x2018 || code === 0x2019) { // single quotes
        finalClean += "'";
      } else if (code === 0x201C || code === 0x201D) { // double quotes
        finalClean += '"';
      } else {
        // Skip code
      }
    }
  }

  return finalClean.replace(/\s+/g, ' ').trim();
}

/**
 * addAllHeaders: Systematically draws a premium branded header on every page.
 */
function addAllHeaders(doc, title, module, icon, pageType) {
  const totalPages = doc.internal.getNumberOfPages();
  const cleanTitle = cleanTextForPdf(title);
  const cleanModule = cleanTextForPdf(module);
  const headerH = 22;

  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    
    // Yellow banner background
    doc.setFillColor(...COLORS.yellow);
    doc.rect(0, 0, PAGE_WIDTH, headerH, 'F');
    
    // Bottom neo-brutalist border line
    doc.setDrawColor(...COLORS.black);
    doc.setLineWidth(1.0);
    doc.line(0, headerH, PAGE_WIDTH, headerH);

    // Title text
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(...COLORS.black);
    doc.text(cleanTitle, MARGIN.left, 14);

    // Module + Type badge
    doc.setFontSize(8);
    doc.setFont('helvetica', 'normal');
    const badgeText = `${cleanModule}  |  ${pageType}`;
    const badgeW = doc.getTextWidth(badgeText) + 8;
    const badgeX = PAGE_WIDTH - MARGIN.right - badgeW;
    
    doc.setFillColor(...COLORS.white);
    doc.setDrawColor(...COLORS.black);
    doc.setLineWidth(0.6);
    doc.roundedRect(badgeX, 5, badgeW, 12, 1.5, 1.5, 'FD');
    doc.text(badgeText, badgeX + 4, 13);
  }
}

function addFooter(doc, pageNum, totalPages) {
  const y = 297 - 12;
  doc.setDrawColor(...COLORS.black);
  doc.setLineWidth(0.3);
  doc.line(MARGIN.left, y - 4, PAGE_WIDTH - MARGIN.right, y - 4);
  
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(...COLORS.gray);
  doc.text('Generated by CS Simulator  |  Placement-Ready Study Material', MARGIN.left, y);
  doc.text(`Page ${pageNum} / ${totalPages}`, PAGE_WIDTH - MARGIN.right, y, { align: 'right' });
}

function addAllFooters(doc) {
  const totalPages = doc.internal.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    addFooter(doc, i, totalPages);
  }
}

function checkPageBreak(doc, y, needed = 30) {
  if (y + needed > 297 - MARGIN.bottom) {
    doc.addPage();
    return MARGIN.top;
  }
  return y;
}

function drawSectionHeading(doc, text, y, color = COLORS.cyan) {
  y = checkPageBreak(doc, y, 22);
  const cleanText = cleanTextForPdf(text);
  
  // Neo-brutalist colored heading block
  doc.setFillColor(...color);
  doc.setDrawColor(...COLORS.black);
  doc.setLineWidth(0.8);
  doc.roundedRect(MARGIN.left, y, CONTENT_WIDTH, 12, 1.5, 1.5, 'FD');
  
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(...COLORS.black);
  doc.text(cleanText, MARGIN.left + 4, y + 8.5);
  
  return y + 18; // Adequate vertical spacing below heading
}

function drawBodyText(doc, text, y, indent = 0) {
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(...COLORS.darkGray);
  
  const maxWidth = CONTENT_WIDTH - indent;
  const lines = doc.splitTextToSize(cleanTextForPdf(text), maxWidth);
  
  for (const line of lines) {
    y = checkPageBreak(doc, y, 7);
    doc.text(line, MARGIN.left + indent, y);
    y += 5.5; // Improved line spacing
  }
  
  return y + 2.5; // Padding after paragraphs
}

function drawCodeBlock(doc, code, y) {
  const lines = code.split('\n');
  const lineHeight = 5.0;
  const padding = 6;
  const blockHeight = lines.length * lineHeight + padding * 2;
  
  y = checkPageBreak(doc, y, blockHeight + 6);
  
  // Neo-brutalist offset drop shadow
  doc.setFillColor(...COLORS.black);
  doc.roundedRect(MARGIN.left + 5.5, y - 0.5, CONTENT_WIDTH - 8, blockHeight, 2, 2, 'F');
  
  // Code block container
  doc.setFillColor(30, 30, 46); // Dark editor-style theme
  doc.setDrawColor(...COLORS.black);
  doc.setLineWidth(0.8);
  doc.roundedRect(MARGIN.left + 4, y - 2, CONTENT_WIDTH - 8, blockHeight, 2, 2, 'FD');
  
  doc.setFont('courier', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(205, 214, 244); // Catppuccin text color
  
  let currentY = y + padding + 1;
  for (const line of lines) {
    doc.text(cleanTextForPdf(line), MARGIN.left + 9, currentY);
    currentY += lineHeight;
  }
  
  return y + blockHeight + 5;
}

function drawDifficultyBadge(doc, difficulty, x, y) {
  const colors = {
    'Easy': COLORS.green,
    'Medium': COLORS.orange,
    'Hard': COLORS.pink,
  };
  const color = colors[difficulty] || COLORS.gray;
  const w = doc.getTextWidth(difficulty) + 8;
  
  doc.setFillColor(...color);
  doc.setDrawColor(...COLORS.black);
  doc.setLineWidth(0.4);
  doc.roundedRect(x, y - 3.5, w, 6, 1.5, 1.5, 'FD');
  
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(6.5);
  doc.setTextColor(...COLORS.black);
  doc.text(difficulty, x + 4, y + 0.5);
  
  return w;
}

/* ═══════════════════════════════════════
   SUBHEADING UTILITY
   ═══════════════════════════════════════ */
function drawSubheading(doc, text, y) {
  y = checkPageBreak(doc, y, 15);
  const cleanText = cleanTextForPdf(text);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.setTextColor(...COLORS.black);
  doc.text(cleanText, MARGIN.left + 2, y);
  
  doc.setDrawColor(210, 210, 210);
  doc.setLineWidth(0.3);
  doc.line(MARGIN.left + 2, y + 1.5, PAGE_WIDTH - MARGIN.right, y + 1.5);
  
  return y + 7.5;
}

